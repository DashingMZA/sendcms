import { defineConfig, globalIgnores } from "eslint/config"
import baseConfig from "@sendcms/config/eslint/base.mjs"

const eslintConfig = defineConfig([
  // Shared SendCMS base (Next.js presets from @sendcms/config).
  ...baseConfig,
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
    // Generated output, anywhere in the workspace (the root lint runs
    // from the repo root and traverses the apps/ + packages/ trees, so
    // these must be globbed, not root-anchored — the apps' own configs
    // ignore only their own .next/):
    "**/.next/**",
    // OpenNext build output (generated by the Cloudflare build). Without
    // this, eslint traverses the whole generated tree and OOMs (Phase 11).
    "**/.open-next/**",
    // Built SDK bundles (generated by pnpm sdk:build — served by the
    // api app from public/forms/ since Phase 8).
    "**/public/forms/**",
    // Generated Prisma client (packages/database/generated/prisma).
    "packages/database/generated/**",
    // Git worktrees live inside the repo root — exclude so ESLint doesn't
    // traverse into them and pick up their node_modules.
    ".claude/worktrees/**",
  ]),
])

export default eslintConfig
